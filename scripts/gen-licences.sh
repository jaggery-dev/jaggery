#!/bin/sh
# Writes internal/licences/licences.txt: Jaggery's own LICENSE and NOTICE,
# then the licence of Go and of every module built into jag on any release
# platform. jag embeds the file and prints it with jag licences, which is how
# a copy of jag carries the notices its dependencies' licences ask for. Run it
# after adding, removing or upgrading a dependency:
#   sh scripts/gen-licences.sh
# CI runs it with --check, which fails if the committed file is out of date.
set -eu
cd "$(git rev-parse --show-toplevel)"
check=false
case "${1:-}" in
  --check) check=true ;;
  "") ;;
  *) echo "usage: sh scripts/gen-licences.sh [--check]" >&2; exit 2 ;;
esac
target=internal/licences/licences.txt
out=$(mktemp)
list=$(mktemp)
trap 'rm -f "$out" "$list"' EXIT
# go:embed needs the file to exist before the package can be listed.
[ -f "$target" ] || : > "$target"

# The same platforms as release.yml: a module used on one of them only still
# ships in that build.
for t in linux/amd64 linux/arm64 linux/arm darwin/arm64 darwin/amd64 windows/amd64; do
  GOOS=${t%/*} GOARCH=${t#*/} CGO_ENABLED=0 go list -deps \
    -f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' ./cmd/jag >> "$list"
done
modules=$(sort -u "$list")

rule() { printf '\n%s\n\n' "================================================================================"; }

# Each module's LICENSE (or COPYING), and PATENTS where it has one.
notices() {
  found=false
  for f in LICENSE LICENSE.md LICENSE.txt COPYING PATENTS; do
    if [ -f "$1/$f" ]; then
      printf -- '-- %s\n\n' "$f"
      cat "$1/$f"
      found=true
    fi
  done
  if ! $found; then
    echo "no licence file in $1" >&2
    exit 1
  fi
}

{
  echo "Jaggery and the software built into it"
  echo
  echo "Generated by scripts/gen-licences.sh; don't edit by hand."
  rule
  echo "Jaggery"
  echo
  cat NOTICE
  echo
  cat LICENSE
  rule
  echo "Go, its standard library and runtime"
  echo
  notices "$(go env GOROOT)"
  for m in $modules; do
    v=$(go list -m -f '{{.Version}}' "$m")
    dir=$(go list -m -f '{{.Dir}}' "$m")
    rule
    echo "$m $v"
    echo
    notices "$dir"
  done
} > "$out"

if $check; then
  if ! diff -u "$target" "$out" > /dev/null; then
    diff -u "$target" "$out" | head -40
    echo "$target is out of date: run sh scripts/gen-licences.sh and commit it" >&2
    exit 1
  fi
  echo "$target is up to date"
  exit 0
fi
cp "$out" "$target"
echo "wrote $target"
